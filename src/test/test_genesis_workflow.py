import asyncio, json
from pathlib import Path
from playwright.async_api import async_playwright
S = Path('/tmp/browser/genesis')
S.mkdir(parents=True, exist_ok=True)
async def main():
 async with async_playwright() as p:
  browser = await p.chromium.launch(headless=True)
  context = await browser.new_context(viewport={'width':1280,'height':1800})
  page = await context.new_page()
  errors=[]; external=[]
  page.on('pageerror', lambda error: errors.append(str(error)))
  page.on('request', lambda req: external.append(req.url) if any(x in req.url for x in ['api.github.com','api.stripe.com','/rest/v1/','/auth/v1/']) else None)
  await page.goto('http://localhost:8080/embassy',wait_until='networkidle')
  await page.get_by_role('button',name='Join as Developer',exact=True).click()
  await page.get_by_label('Human name / attribution').fill('Sample Genesis Author')
  for name in ['Submit documented capsules','Run synthetic twin models']:
   await page.get_by_label(name,exact=True).check()
  await page.get_by_label('I opt into this local demo',exact=False).check()
  await page.get_by_role('button',name='Record local identity',exact=True).click()
  await page.get_by_role('heading',name='Sample Genesis Author',exact=True).wait_for()
  await page.get_by_role('button',name='Join as Human',exact=True).click()
  await page.get_by_label('Human name / attribution').fill('Sample Genesis Reviewer')
  await page.get_by_label('Recommend review decisions',exact=True).check()
  await page.get_by_label('I opt into this local demo',exact=False).check()
  await page.get_by_role('button',name='Record local identity',exact=True).click()
  await page.get_by_role('heading',name='Sample Genesis Reviewer',exact=True).wait_for()
  await page.screenshot(path=str(S/'1_embassy.png'))
  await page.goto('http://localhost:8080/challenges',wait_until='networkidle')
  await page.get_by_role('button',name='Submit a Challenge',exact=True).click()
  dialog=page.get_by_role('dialog')
  await dialog.get_by_label('Local challenge creator',exact=True).select_option(label='Sample Genesis Author · Developer')
  await dialog.get_by_label('Challenge title',exact=True).fill('Sample keyboard workflow challenge')
  await dialog.get_by_label('Technical problem',exact=True).fill('Document predictable keyboard focus selection with bounded behavior for an empty list.')
  await dialog.get_by_label('Acceptance criteria and judging rubric',exact=True).fill('Provide source attribution, a rollback plan and a reproducible keyboard boundary test plan.')
  await dialog.get_by_label('Proposed bounty',exact=False).fill('1200')
  await dialog.get_by_role('button',name='Save local challenge proposal',exact=True).click()
  await page.get_by_role('heading',name='Sample keyboard workflow challenge',exact=True).wait_for()
  challenge_url=page.url
  await page.get_by_label('Local submitting identity',exact=True).select_option(label='Sample Genesis Author · Developer')
  await page.get_by_label('Capsule title',exact=True).fill('Sample keyboard evidence capsule')
  await page.get_by_label('What it does, compatibility and limitations',exact=True).fill('Documented keyboard boundary behavior with limitations; no accessibility certification claimed.')
  await page.get_by_label('Code Exchange reference',exact=False).select_option('keyboard-navigation')
  await page.get_by_label('Code sample',exact=False).fill("export const sample = 'stored_as_text_only';")
  await page.get_by_label('Declared capsule license',exact=False).select_option('MIT')
  await page.get_by_label('Dependencies and source/license status',exact=True).fill('No dependencies; original sample rights self-declared, independent review pending.')
  await page.get_by_label('Reproducible tests and evidence plan',exact=True).fill('Check Home, End and empty-list behavior in a keyboard-accessible parent widget.')
  await page.get_by_label('Rollback and risk notes',exact=True).fill('Restore the prior approved keyboard handler on any regression and check focus order.')
  await page.get_by_label('I declare permission to share',exact=False).check()
  await page.get_by_role('button',name='Submit local documented capsule',exact=True).click()
  await page.get_by_role('heading',name='Sample keyboard evidence capsule',exact=True).wait_for()
  capsule_url=page.url
  await page.get_by_role('link',name='Configure synthetic twin',exact=True).click()
  await page.get_by_role('heading',name='Digital Twin Lab',exact=True).wait_for()
  await page.get_by_label('Local simulation runner',exact=True).select_option(label='Sample Genesis Author · Developer')
  await page.get_by_role('button',name='Run synthetic model',exact=True).click()
  await page.get_by_text('80',exact=False).last.wait_for()
  await page.screenshot(path=str(S/'2_twin.png'))
  await page.goto(capsule_url,wait_until='networkidle')
  await page.get_by_label('Local reviewer identity',exact=True).select_option(label='Sample Genesis Reviewer · Human')
  await page.get_by_label('Decision',exact=False).select_option('Demo approve')
  await page.get_by_label('Reason, evidence gaps and security/license findings',exact=True).fill('Local demo review of documented assumptions only. No real certification or production approval.')
  await page.get_by_role('button',name='Record demo reviewer decision',exact=True).click()
  await page.get_by_role('button',name='Prepare demo marketplace listing',exact=True).click()
  await page.reload(wait_until='networkidle')
  await page.get_by_text('Demo listed',exact=True).first.wait_for()
  async with page.expect_download() as downloaded:
   await page.get_by_role('button',name='Download unsigned demo manifest',exact=True).click()
  manifest=json.loads(Path(await (await downloaded.value).path()).read_text())
  assert manifest['signature'] is None and manifest['distribution']=='DISABLED'
  assert manifest['reward']=={'currency':'USD','price':'TBD','funded':False,'payout':None}
  await page.screenshot(path=str(S/'3_capsule_review.png'))
  await page.goto('http://localhost:8080/marketplace',wait_until='networkidle')
  await page.get_by_role('heading',name='Sample keyboard evidence capsule',exact=True).wait_for()
  assert await page.get_by_role('button',name='Purchase · disabled',exact=True).is_disabled()
  await page.screenshot(path=str(S/'4_marketplace.png'))
  await page.goto('http://localhost:8080/pulse',wait_until='networkidle')
  await page.get_by_text('Prepared demo marketplace listing · USD TBD / no payout',exact=True).wait_for()
  await page.goto('http://localhost:8080/sdk',wait_until='networkidle')
  await page.get_by_role('button',name='Validate JSON locally',exact=True).click()
  await page.get_by_text('Valid contract shape.',exact=False).wait_for()
  await page.get_by_label('Contract JSON',exact=True).fill('{"mode":"LIVE"}')
  await page.get_by_role('button',name='Validate JSON locally',exact=True).click()
  await page.get_by_text('Contract validation failed.',exact=True).wait_for()
  await page.get_by_role('button',name='Reset example',exact=True).click()
  await page.screenshot(path=str(S/'5_sdk.png'))
  await page.goto('http://localhost:8080/challenges',wait_until='networkidle')
  await page.get_by_label('Search challenges',exact=True).fill('Sample keyboard')
  assert await page.get_by_role('link',name='Sample keyboard workflow challenge',exact=True).count()==1
  await page.get_by_label('Challenge domain',exact=True).select_option('Banking')
  await page.get_by_text('No matching challenges.',exact=True).wait_for()
  await page.get_by_role('button',name='Reset filters',exact=True).click()
  await page.goto('http://localhost:8080/discovery',wait_until='networkidle')
  await page.get_by_label('Search discovery',exact=True).fill('Sample keyboard evidence')
  await page.get_by_role('link',name='Sample keyboard evidence capsule',exact=True).wait_for()
  await page.set_viewport_size({'width':390,'height':844})
  await page.goto('http://localhost:8080/challenges',wait_until='networkidle')
  await page.get_by_role('button',name='Open menu',exact=True).click()
  await page.get_by_role('navigation',name='Mobile',exact=True).get_by_role('link',name='Agent Embassy',exact=True).click()
  await page.get_by_role('heading',name='Agent Embassy',exact=True).wait_for()
  assert not await page.get_by_role('navigation',name='Mobile',exact=True).count()
  await page.screenshot(path=str(S/'6_mobile_embassy.png'))
  for path in ['/challenges','/sdk','/digital-twin','/compute-grid','/trust','/releases','/code-exchange',capsule_url.replace('http://localhost:8080','')]:
   await page.goto('http://localhost:8080'+path,wait_until='networkidle')
   overflow=await page.evaluate('document.documentElement.scrollWidth > window.innerWidth')
   assert not overflow, 'mobile overflow '+path
  await page.screenshot(path=str(S/'7_mobile_capsule.png'))
  await page.goto('http://localhost:8080/embassy',wait_until='networkidle')
  reviewer=page.get_by_role('button',name='Revoke local consent for Sample Genesis Reviewer',exact=True)
  await reviewer.click()
  await page.goto(capsule_url,wait_until='networkidle')
  await page.get_by_text('Changes requested',exact=True).first.wait_for()
  assert await page.get_by_role('button',name='Prepare demo marketplace listing',exact=True).is_disabled()
  await page.goto('http://localhost:8080/marketplace',wait_until='networkidle')
  await page.get_by_text('No demo listings yet.',exact=False).wait_for()
  await page.screenshot(path=str(S/'8_revoked_marketplace.png'))
  assert not external, external
  assert not errors, errors
  print('PASS: challenge',challenge_url,'capsule',capsule_url,'reload, review, unsigned download, marketplace, Pulse, SDK validation, filters and mobile; no external auth/API calls; no runtime errors')
  await browser.close()
asyncio.run(main())
